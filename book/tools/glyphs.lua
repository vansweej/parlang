-- Glyph coverage table generator for the ParLang book.
--
-- Usage: texlua book/tools/glyphs.lua <out.tex> <source>...
-- Collects every distinct non-ASCII code point in the sources and writes a
-- longtable with one row per code point (sorted): U+XXXX, the character in
-- the serif, sans and mono fonts, and the first source file using it.
-- Invisible code points (controls, combining marks, format characters,
-- variation selectors, tags) print "(invisible)" instead of the character.

if #arg < 2 then
  error("usage: texlua book/tools/glyphs.lua <out.tex> <source>...")
end

local out_path = arg[1]
local first_seen = {}
local codes = {}

local function is_invisible(code)
  return (code >= 0x80 and code <= 0x9F)
    or code == 0xA0
    or code == 0xAD
    or (code >= 0x300 and code <= 0x36F)
    or (code >= 0x200B and code <= 0x200F)
    or (code >= 0x2028 and code <= 0x202F)
    or (code >= 0x2060 and code <= 0x206F)
    or (code >= 0xFE00 and code <= 0xFE0F)
    or code == 0xFEFF
    or code >= 0xE0000
end

local function collect(path)
  local handle = io.open(path, "rb")
  if not handle then
    error("glyphs.lua: cannot read " .. path)
  end
  local text = handle:read("a")
  handle:close()
  local ok, err = pcall(function()
    for _, code in utf8.codes(text) do
      if code > 0x7F and first_seen[code] == nil then
        first_seen[code] = path
        codes[#codes + 1] = code
      end
    end
  end)
  if not ok then
    error("glyphs.lua: invalid UTF-8 in " .. path .. ": " .. tostring(err))
  end
end

local function row(code, path)
  local label = string.format("U+%04X", code)
  local where = "\\texttt{\\detokenize{" .. path .. "}}"
  if is_invisible(code) then
    return label .. " & (invisible) & & & " .. where .. " \\\\"
  end
  local ch = utf8.char(code)
  return label .. " & " .. ch .. " & {\\sffamily " .. ch .. "} & \\texttt{" .. ch .. "} & " .. where .. " \\\\"
end

for i = 2, #arg do
  collect(arg[i])
end
table.sort(codes)

local lines = {
  "% Generated by book/tools/glyphs.lua; do not edit.",
  string.format("Distinct non-ASCII code points: %d.", #codes),
  "",
  "\\begin{longtable}{lllll}",
  "\\toprule",
  "Code point & Serif & Sans & Mono & First source \\\\",
  "\\midrule",
  "\\endhead",
}
for _, code in ipairs(codes) do
  lines[#lines + 1] = row(code, first_seen[code])
end
lines[#lines + 1] = "\\bottomrule"
lines[#lines + 1] = "\\end{longtable}"

local out = io.open(out_path, "wb")
if not out then
  error("glyphs.lua: cannot write " .. out_path)
end
out:write(table.concat(lines, "\n"), "\n")
out:close()
